/**
 * Regenerates the demo audio clips and their manifest.
 *
 *   npx tsx scripts/make-demo-clips.ts
 *
 * macOS only: clips are synthesised with `say` and converted with `afconvert`
 * to 16 kHz mono 16-bit WAV, the format both platform recognisers accept as
 * file input. They stand in for a learner speaking on a simulator; they are
 * not used for anything a real learner hears.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { scenariosFor } from '../src/features/conversation/content';
import { demoReviewCards } from '../src/features/demo/content/learner';
import { clipKey } from '../src/features/demo/lib/clipKey';
import { placementQuestions } from '../src/features/onboarding/content/placementQuestions';
import { drillsFor } from '../src/features/pronunciation/content/drills';

const LANGUAGE = 'es';
const VOICE = 'Mónica';
const root = join(__dirname, '..');
const outDir = join(root, 'assets', 'audio', LANGUAGE);

const texts = new Set<string>();
for (const scenario of scenariosFor(LANGUAGE)) {
  for (const step of scenario.steps) texts.add(step.demoUtterance);
}
for (const drill of drillsFor(LANGUAGE)) texts.add(drill.text);
for (const question of placementQuestions[LANGUAGE]) {
  if (question.kind === 'speaking') texts.add(question.sentence);
}
for (const card of demoReviewCards) texts.add(card.answer);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const entries: string[] = [];
for (const text of [...texts].sort()) {
  const key = clipKey(LANGUAGE, text);
  const file = `${key.split('/')[1]}.wav`;
  const aiff = join(outDir, `${file}.aiff`);
  execFileSync('say', ['-v', VOICE, '-r', '165', '-o', aiff, text]);
  execFileSync('afconvert', [
    '-f',
    'WAVE',
    '-d',
    'LEI16@16000',
    '-c',
    '1',
    aiff,
    join(outDir, file),
  ]);
  rmSync(aiff);
  entries.push(`  '${key}': require('../../../assets/audio/${LANGUAGE}/${file}'),`);
}

writeFileSync(
  join(root, 'src', 'features', 'demo', 'clipManifest.ts'),
  [
    '// Generated by scripts/make-demo-clips.ts. Do not edit by hand.',
    'export const clipManifest: Record<string, number> = {',
    ...entries,
    '};',
    '',
  ].join('\n'),
);
console.log(`Wrote ${entries.length} clips to ${outDir}`);
